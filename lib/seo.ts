import { OG_PAGES, SITE_NAME, SITE_URL } from "@/constants/site";
import { getPathname, routing } from "@/i18n/routing";
import type { CollectionSchemaType } from "@/lib/articles/collections";
import type { ArticleEntry } from "@/lib/articles/parse";
import type { StaticHref } from "@/i18n/pathnames";
import { entryLogicalPath, ogImagePath, socialImageMetadata } from "@/lib/og/model";
import type { Metadata } from "next";

// Logical key of a STATIC route (i18n/pathnames.ts); dynamic `[param]` routes excluded.
export type LogicalHref = StaticHref<typeof routing.pathnames>;

const absolute = (pathname: string) => new URL(pathname, SITE_URL).toString();

// Logical key of a collection ENTRY route ("/articles/[slug]", "/reminders/[slug]"…).
export type EntryHref = Extract<keyof typeof routing.pathnames, `${string}/[slug]`>;

// Localized path of an entry translation of a collection (its slug differs per locale).
export function entryPath(itemHref: EntryHref, locale: string, slug: string): string {
    // The union of entry keys is narrowed to one key for the typed overloads of getPathname.
    return getPathname({ locale, href: { pathname: itemHref as "/articles/[slug]", params: { slug } } });
}

// Absolute canonical URL of an entry translation (SITE_URL + its localized path).
export function entryUrl(itemHref: EntryHref, locale: string, slug: string): string {
    return absolute(entryPath(itemHref, locale, slug));
}

// Localized path of an article translation (the default collection).
export function articlePath(locale: string, slug: string): string {
    return entryPath("/articles/[slug]", locale, slug);
}

// Shared core: `urls` = absolute URL of the SAME resource in every locale where it exists.
// canonical = the page's OWN locale URL (a translation is not a duplicate of the default
// locale); x-default = the default-locale version, else the page itself.
// The social image (og:image + twitter:image, 1200x630 PNG generated by app/og/[locale]/[...path]):
// `imagePath` = LOGICAL path of the drawn page in the page's locale (lib/og/model.ts), `alt` = what
// the image shows (the page title, or the site name for the shared home image).
function localizedMetadata(opts: {
    title: string;
    description: string;
    locale: string;
    urls: Record<string, string>;
    image: { path: string; alt: string };
}): Metadata & { alternates: { canonical: string; languages: Record<string, string> } } {
    const canonical = opts.urls[opts.locale];
    const languages = { ...opts.urls, "x-default": opts.urls[routing.defaultLocale] ?? canonical };
    const { images, twitter } = socialImageMetadata({
        url: absolute(ogImagePath(opts.locale, opts.image.path)),
        alt: opts.image.alt,
        title: opts.title,
        description: opts.description,
    });
    return {
        title: opts.title,
        description: opts.description,
        alternates: { canonical, languages },
        openGraph: {
            title: opts.title,
            description: opts.description,
            url: canonical,
            type: "website",
            locale: opts.locale,
            images,
        },
        twitter,
    };
}

// Localized metadata + hreflang + social image, reused by every static page.
// href = LOGICAL KEY of the pathnames mapping (never a concatenated localized slug). A page listed in
// OG_PAGES (constants/site.ts: the app's pages and the collection listings) gets its own image; any other page
// shares the home image.
export function pageMetadata(opts: {
    title: string;
    description: string;
    href: LogicalHref;
    locale: string;
}): Metadata {
    const urls: Record<string, string> = {};
    for (const locale of routing.locales) urls[locale] = absolute(getPathname({ locale, href: opts.href }));
    const own = Object.hasOwn(OG_PAGES, opts.href);
    const image = own ? { path: opts.href, alt: opts.title } : { path: "/", alt: SITE_NAME };
    return localizedMetadata({ ...opts, urls, image });
}

// Article (collection entry) metadata: hreflang lists ONLY the locales that really have a translation.
export function articleMetadata(
    entry: ArticleEntry,
    locale: string,
    itemHref: EntryHref = "/articles/[slug]",
): Metadata {
    const article = entry.translations[locale];
    const urls: Record<string, string> = {};
    for (const [l, translation] of Object.entries(entry.translations))
        urls[l] = absolute(entryPath(itemHref, l, translation.slug));
    // The generated card embeds the front-matter `image` (when it has one) as a thumbnail, so the
    // shared image is always a 1200x630 PNG, whatever the cover's format or ratio.
    const image = { path: entryLogicalPath(itemHref, article.slug), alt: article.title };
    const base = localizedMetadata({ title: article.title, description: article.description, locale, urls, image });
    return {
        ...base,
        openGraph: {
            ...base.openGraph,
            type: "article",
            publishedTime: article.date,
        },
    };
}

// schema.org entry (BlogPosting for articles; a collection picks its type), serialized into a
// <script type="application/ld+json">.
export function articleJsonLd(
    entry: ArticleEntry,
    locale: string,
    siteName: string,
    {
        itemHref = "/articles/[slug]",
        schemaType = "BlogPosting",
    }: { itemHref?: EntryHref; schemaType?: CollectionSchemaType } = {},
): string {
    const article = entry.translations[locale];
    const url = absolute(entryPath(itemHref, locale, article.slug));
    const data = {
        "@context": "https://schema.org",
        "@type": schemaType,
        headline: article.title,
        description: article.description,
        datePublished: article.date,
        inLanguage: locale,
        url,
        mainEntityOfPage: url,
        publisher: { "@type": "Organization", name: siteName },
        ...(article.image ? { image: absolute(article.image) } : {}),
    };
    // "<" escaped so that no content can close the script element.
    return JSON.stringify(data).replace(/</g, "\\u003c");
}
